const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function fmtNum(n, lang = 'bn') {
  const s = String(n);
  if (lang !== 'bn') return s;
  return s.replace(/\d/g, (d) => BN_DIGITS[Number(d)]);
}

